//print small a to z and caps A to Z 

#include<iostream>
using namespace std;
int main()
{
    //caps A to Z
    for(char c='A';c<='Z';c++)
    {
        cout<<c<<" ";
    }
    cout<<"\n";


    //  small a to z
     for(char s='a';s<='z';s++)
    {
        cout<<s<<" ";
    }
    cout<<"\n";
 
    return 0; 

}